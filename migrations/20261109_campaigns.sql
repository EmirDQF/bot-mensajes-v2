-- Promociones a pacientes anteriores (pestaña Campañas) con opt-in de marketing. Idempotente.
-- Ejecutar después de 20261107_ethical_follow_ups.sql. Sin esta migración la pestaña Campañas avisa que falta y el
-- bot no pregunta por el permiso de promociones; todo lo demás sigue funcionando.

-- Permiso de promociones: cuándo se preguntó y el texto exacto que aceptó el paciente.
ALTER TABLE IF EXISTS public.contact_preferences ADD COLUMN IF NOT EXISTS marketing_asked_at TIMESTAMPTZ;
ALTER TABLE IF EXISTS public.contact_preferences ADD COLUMN IF NOT EXISTS marketing_opt_in_text TEXT;

CREATE TABLE IF NOT EXISTS public.campaigns (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  clinic_id TEXT NOT NULL,
  name TEXT NOT NULL,
  promotion_text TEXT NOT NULL,
  segment JSONB NOT NULL,
  scheduled_at TIMESTAMPTZ NOT NULL,
  status TEXT NOT NULL DEFAULT 'programada'
    CHECK (status IN ('programada', 'enviando', 'terminada', 'pausada', 'cancelada')),
  status_reason TEXT,
  estimated_recipients INTEGER,
  estimated_cost NUMERIC(10, 4),
  price_per_message NUMERIC(10, 4),
  currency TEXT,
  confirmed_by TEXT NOT NULL,
  confirmed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  finished_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS campaigns_clinic_status_idx ON public.campaigns (clinic_id, status, scheduled_at);
ALTER TABLE public.campaigns ENABLE ROW LEVEL SECURITY;

-- Un envío por campaña y paciente (el índice único evita duplicar aunque el cron corra dos veces).
CREATE TABLE IF NOT EXISTS public.campaign_recipients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id UUID NOT NULL REFERENCES public.campaigns(id) ON DELETE CASCADE,
  clinic_id TEXT NOT NULL,
  phone TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'enviando' CHECK (status IN ('enviando', 'enviado', 'fallido', 'omitido')),
  wamid TEXT,
  error TEXT,
  sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS campaign_recipients_campaign_phone_uidx ON public.campaign_recipients (campaign_id, phone);
-- Regla de los 14 días: último envío de promoción por paciente.
CREATE INDEX IF NOT EXISTS campaign_recipients_clinic_phone_sent_idx ON public.campaign_recipients (clinic_id, phone, sent_at DESC);
ALTER TABLE public.campaign_recipients ENABLE ROW LEVEL SECURITY;
